/**
 * Заставка.
 *
 * ⚠️ При ПЕРВОЙ загрузке заставки больше НЕТ - снята по решению Марка
 * (02.08, подтверждено 07.08): она держала человека до 3.5 секунд до
 * контента, на платном трафике это прямой минус к заявкам. Страница
 * отдаётся готовым HTML сразу.
 *
 * Осталась одна работа - прикрывать СМЕНУ ЯЗЫКА: полотно опускается,
 * за ним подменяются все тексты, полотно уходит. Без этого буквы скачут
 * на глазах, а длина строк на английском другая - выглядит как сбой.
 */
export function usePreloader() {
  /* По умолчанию скрыта: в готовый HTML не попадает */
  const visible = useState<boolean>('preloader', () => false)

  /** Показать заставку на заданное время (для смены языка) */
  async function hold(ms: number) {
    visible.value = true
    await new Promise((r) => setTimeout(r, ms))
  }

  function hide() {
    visible.value = false
  }

  return { visible, hold, hide }
}
